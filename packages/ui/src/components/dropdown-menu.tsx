/*
 * Pressable rows take `cursor-pointer`, not the `cursor-default` a native menu
 * uses. These sit inside a chat widget on someone else's page, where every
 * other affordance is web-shaped — the composer's own buttons get a pointer
 * from the base stylesheet — so an arrow cursor over a highlighted row read as
 * inert rather than as native.
 */

/*
 * The popup is separated from what it covers by a border and a cast shadow,
 * not by its fill.
 *
 * `--popover` is pure white in the light theme and so is `--background`, which
 * left a menu opened over the chat panel with no edge at all — the items
 * appeared to float in the transcript. A tint deep enough to read as a
 * different surface would be dark enough to read as disabled, so the
 * separation is carried by the border (`--border`, which is a light grey in
 * one theme and a white 10% in the other) and by a two-part shadow: a wide
 * soft one for the lift, a tight one to seat the edge. The dark theme takes a
 * heavier shadow because a dark cast on a dark ground barely registers at the
 * light theme's opacity.
 *
 * A 5% ring was doing this job before and was, in practice, invisible.
 */
function DropdownMenuContent({
  align = "start",
  alignOffset = 0,
  side = "bottom",
  sideOffset = 4,
  className,
  container,
  ...props
}: MenuPrimitive.Popup.Props &
  Pick<
    MenuPrimitive.Positioner.Props,
    "align" | "alignOffset" | "side" | "sideOffset"
  > &
  // Portals default to document.body. Inside a shadow root that escapes the
  // injected stylesheet, so consumers must be able to redirect it.
  Pick<MenuPrimitive.Portal.Props, "container">) {
  return (
    <MenuPrimitive.Portal container={container}>
      <MenuPrimitive.Positioner
        className="isolate z-50 outline-none"
        align={align}
        alignOffset={alignOffset}
        side={side}
        sideOffset={sideOffset}
      >
        <MenuPrimitive.Popup
          data-slot="dropdown-menu-content"
          className={cn(
            "z-50 max-h-(--available-height) w-(--anchor-width) min-w-48 origin-(--transform-origin) overflow-x-hidden overflow-y-auto rounded-2xl border border-border bg-popover p-1 text-popover-foreground shadow-[0_18px_44px_-12px_rgb(0_0_0/0.30),0_6px_14px_-6px_rgb(0_0_0/0.16)] duration-100 outline-none data-[side=bottom]:slide-in-from-top-2 data-[side=inline-end]:slide-in-from-left-2 data-[side=inline-start]:slide-in-from-right-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 dark:shadow-[0_18px_44px_-10px_rgb(0_0_0/0.72),0_6px_14px_-6px_rgb(0_0_0/0.5)] data-open:animate-in data-open:fade-in-0 data-open:zoom-in-95 data-closed:animate-out data-closed:overflow-hidden data-closed:fade-out-0 data-closed:zoom-out-95",
            className
          )}
          {...props}
        />
      </MenuPrimitive.Positioner>
    </MenuPrimitive.Portal>
  )
}

